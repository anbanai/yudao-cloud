package cn.iocoder.yudao.module.member.service.point;

import cn.iocoder.yudao.framework.test.core.ut.BaseDbUnitTest;
import cn.iocoder.yudao.module.member.dal.mysql.user.MemberUserMapper;
import cn.iocoder.yudao.module.member.service.user.MemberUserService;
import jakarta.annotation.Resource;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.springframework.boot.test.mock.mockito.MockBean;
import org.springframework.context.annotation.Import;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.transaction.PlatformTransactionManager;
import org.springframework.transaction.support.TransactionTemplate;

import javax.sql.DataSource;
import java.time.LocalDateTime;
import java.util.concurrent.*;

import static org.junit.jupiter.api.Assertions.*;
import static org.mockito.Mockito.*;

@Import({RecoveredPointCreditService.class, MemberPointBatchServiceImpl.class})
class RecoveredPointCreditTest extends BaseDbUnitTest {
    @Resource private RecoveredPointCreditService credits;
    @Resource private MemberPointBatchService batches;
    @Resource private MemberUserMapper users;
    @Resource private DataSource dataSource;
    @Resource private PlatformTransactionManager transactions;
    @MockBean private MemberUserService userService;
    private JdbcTemplate jdbc;

    @BeforeEach
    void seed() {
        jdbc = new JdbcTemplate(dataSource);
        jdbc.execute("CREATE TABLE IF NOT EXISTS member_point_record(id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,user_id bigint,biz_type int,biz_id varchar(64),point int,total_point int,title varchar(64),description varchar(255),status int,effective_time timestamp,point_calculate_price int,point_give_base int,point_give_multiplier int,creator varchar(64),updater varchar(64),create_time timestamp,update_time timestamp,deleted boolean default false,tenant_id bigint default 0)");
        jdbc.update("DELETE FROM member_point_record");
        jdbc.update("DELETE FROM member_point_batch");
        jdbc.update("INSERT INTO member_user(id,mobile,status,register_ip,point) VALUES (11,'synthetic',0,'test',30)");
        when(userService.getUserForUpdate(11L)).thenAnswer(call -> users.selectByIdForUpdate(11L));
        when(userService.getUser(11L)).thenAnswer(call -> users.selectById(11L));
        when(userService.updateUserPoint(eq(11L),anyInt())).thenAnswer(call -> users.updatePointDecr(11L,call.getArgument(1)) == 1);
    }

    private int credit() {
        return new TransactionTemplate(transactions).execute(status -> credits.credit(11, 77, 100));
    }

    private int number(String query) { return jdbc.queryForObject(query, Integer.class); }

    @Test
    void oneYearFromReceiptAndOnlyUnspentRemainderExpiresOnce() {
        assertEquals(100, credit());
        var earned = jdbc.queryForObject("SELECT earned_time FROM member_point_batch", LocalDateTime.class);
        assertEquals(earned, jdbc.queryForObject("SELECT effective_time FROM member_point_record", LocalDateTime.class));
        assertEquals(earned.plusYears(1), jdbc.queryForObject("SELECT expire_time FROM member_point_batch", LocalDateTime.class));
        batches.expire();
        assertEquals(130, number("SELECT point FROM member_user"));
        jdbc.update("UPDATE member_point_batch SET remaining_point=60, expire_time=DATEADD('DAY',-1,CURRENT_TIMESTAMP)");
        jdbc.update("UPDATE member_user SET point=90");
        batches.expire(); batches.expire();
        assertEquals(30, number("SELECT point FROM member_user"));
        assertEquals(-60, number("SELECT point FROM member_point_record WHERE biz_type=25"));
        assertEquals(2, number("SELECT COUNT(*) FROM member_point_record"));
    }

    @Test
    void onlyNetCreditCanExpire() {
        jdbc.update("UPDATE member_user SET point=-40");
        credit();
        assertEquals(100, number("SELECT original_point FROM member_point_batch"));
        assertEquals(60, number("SELECT remaining_point FROM member_point_batch"));
        jdbc.update("UPDATE member_point_batch SET expire_time=CURRENT_TIMESTAMP"); batches.expire();
        assertEquals(0, number("SELECT point FROM member_user"));
    }

    @Test
    void debtStillNegativeIsNotASilentNoOp() {
        jdbc.update("UPDATE member_user SET point=-150");
        assertEquals(100,credit());
        assertEquals(-50,number("SELECT total_point FROM member_point_record"));
        assertEquals(0,number("SELECT remaining_point FROM member_point_batch"));
        jdbc.update("UPDATE member_point_batch SET expire_time=CURRENT_TIMESTAMP"); batches.expire();
        assertEquals(-50,number("SELECT point FROM member_user"));
    }

    @Test
    void concurrentRetryGrantsOneBatch() throws Exception {
        var workers = Executors.newFixedThreadPool(2);
        var start = new CountDownLatch(1);
        Callable<Integer> submit = () -> { start.await(); return credit(); };
        try {
            var first = workers.submit(submit); var second = workers.submit(submit); start.countDown();
            assertEquals(100, first.get(10,TimeUnit.SECONDS) + second.get(10,TimeUnit.SECONDS));
            assertEquals(1,number("SELECT COUNT(*) FROM member_point_record"));
            assertEquals(1,number("SELECT COUNT(*) FROM member_point_batch"));
            assertEquals(130,number("SELECT point FROM member_user"));
        } finally { workers.shutdownNow(); }
    }

    @Test
    void callerFailureRollsBackAllThreeWrites() {
        assertThrows(IllegalStateException.class, () -> new TransactionTemplate(transactions).executeWithoutResult(tx -> {
            credits.credit(11,77,100); throw new IllegalStateException("synthetic failure");
        }));
        assertEquals(30,number("SELECT point FROM member_user"));
        assertEquals(0,number("SELECT COUNT(*) FROM member_point_record"));
        assertEquals(0,number("SELECT COUNT(*) FROM member_point_batch"));
        assertEquals(100,credit());
    }
}
